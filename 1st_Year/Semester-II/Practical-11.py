exp_list = [10, 11, 12, 13, 14, 15]

# Insert
exp_list.insert(2, 100)
print(exp_list)

# Remove
exp_list.remove(100)
print(exp_list)

# Append
exp_list.append(100)
print(exp_list)

# Length
print(len(exp_list))

# Pop
print(f"Element Removed: {exp_list.pop()}")

# Clear
exp_list.clear()
print(exp_list)
